"""Generate the complete block inventory from authoritative source definitions."""

import argparse
from collections import Counter
from pathlib import Path

from little_tinker_rig.core.block_metadata import CATEGORIES, LEVELS
from little_tinker_rig.core.catalog import families
from little_tinker_rig.core.session import Session
from little_tinker_rig.core.snippets import builtin_snippets, instantiate
from little_tinker_rig.core.variants import variant_bindings, variant_source

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "devs/BLOCK_LIBRARY_INVENTORY.md"


def cell(value):
    return str(value).replace("|", "&#124;").replace("\n", "<br>")


def report():
    snippets = builtin_snippets()
    catalog = families(snippets)
    counts = Counter(family.category for family in catalog)
    lines = [
        "# Block library inventory",
        "",
        "Generated by `tools/catalog_report.py` from block source metadata. "
        "Regenerate this report after changing definitions; it is not a second runtime catalog.",
        "",
        f"The audit accounts for **{len(snippets)} templates in {len(catalog)} families**. "
        "Every original template identity remains loadable and recognizable. "
        "Catalog consolidation changes discovery, not existing saved Python.",
        "",
        "Categories, family links, named variants, and advanced fields are defined "
        "in the Python modules. An alias is a retained source form without a separate "
        "ordinary variant-menu entry; an existing lesson may still select its exact identity.",
        "",
        "Execution details below are the authored operation contract. Parameter "
        "annotations describe units and device requirements; expression results retain "
        "their declared type or ordinary Python inference. Source links expose complete "
        "implementations, including compound action termination and cleanup. Hardware "
        "support follows those types and the selected runtime profile, not category membership.",
        "",
        "| Category | Families |",
        "|---|---:|",
    ]
    lines.extend(f"| {title} | {counts[key]} |" for key, title in CATEGORIES.items())
    lines += ["", "| Level | Cumulative available families |", "|---|---:|"]
    lines.extend(
        f"| {level.title()} | {sum(bool(family.choices(level)) for family in catalog)} |"
        for level in LEVELS
    )
    for category, title in CATEGORIES.items():
        lines += ["", f"## {title}"]
        for family in catalog:
            if family.category != category:
                continue
            lines += ["", f"### {family.identity}", ""]
            lines += [
                f"Catalog path: {' → '.join((title, *family.primary.group))}. "
                f"Card title: **{family.primary.title or family.identity}**.",
                "",
            ]
            for snippet in family.members:
                disposition = (
                    "Keep family entry"
                    if snippet.identity == family.identity
                    else (
                        "Consolidate variant"
                        if snippet.catalog_visible
                        else "Retain compatibility alias"
                    )
                )
                kind = (
                    f"expression → {snippet.result_type or 'inferred Python value'}"
                    if snippet.expression
                    else "statement"
                )
                if snippet.context:
                    kind += f"; {snippet.context} context"
                if snippet.readout:
                    kind += "; measurement readout"
                source = snippet.source_path.relative_to(ROOT).as_posix()
                lines += [
                    f"**`{snippet.identity}`** — {disposition}.",
                    "",
                    f"[{source}](../{source}); {snippet.level}; {kind}; "
                    f"{snippet.mode} expansion.",
                    "",
                    f"Variant: {snippet.variant or ('Default' if snippet.catalog_visible else 'Compatibility form')}.",
                    "",
                ]
                if snippet.parameters:
                    lines += [
                        "| Parameter | Type / units | Default | Card field | Shared family field |",
                        "|---|---|---|---|---|",
                    ]
                    for parameter in snippet.parameters:
                        lines.append(
                            "| "
                            + " | ".join(
                                cell(value)
                                for value in (
                                    parameter.name,
                                    parameter.annotation or "Python expression",
                                    (
                                        f"`{parameter.default}`"
                                        if parameter.default is not None
                                        else "Required"
                                    ),
                                    (
                                        "Additional"
                                        if parameter.name in snippet.advanced
                                        else "Essential"
                                    ),
                                    snippet.bindings.get(
                                        parameter.name, parameter.name
                                    ),
                                )
                            )
                            + " |"
                        )
                    lines.append("")
                lines += [snippet.help, ""]
    return "\n".join(lines).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--verify-transitions", action="store_true")
    args = parser.parse_args()
    text = report()
    if args.check:
        if not REPORT.exists() or REPORT.read_text(encoding="utf-8") != text:
            raise SystemExit("Regenerate devs/BLOCK_LIBRARY_INVENTORY.md")
        print("Block inventory: OK")
    else:
        REPORT.write_text(text, encoding="utf-8")
        print(REPORT.relative_to(ROOT))
    if args.verify_transitions:
        count = 0
        for family in families(builtin_snippets()):
            if len(family.members) < 2:
                continue
            for original in family.members:
                source = instantiate(
                    original,
                    {p.name: p.name for p in original.parameters if p.default is None},
                ).source
                session = Session.fragment(source, family.members)
                before = session.document.state
                session.editor.selection = session.document.syntax.tree.body[-1]
                match = session.selected_match()
                if match is None:
                    raise ValueError(f"Unrecognized family form: {original.identity}")
                for target in family.choices():
                    prepared = variant_source(
                        session, match, target, variant_bindings(session, match, target)
                    )
                    checked = Session.fragment(prepared, family.members)
                    if (
                        not checked.matches
                        or checked.matches[0].snippet.catalog_id != family.identity
                    ):
                        raise ValueError(
                            f"Unrecognized transition: {original.identity} → {target.identity}"
                        )
                    if (
                        session.document.state is not before
                        or session.document.can_undo
                    ):
                        raise ValueError("A transition preview changed document state")
                    count += 1
        print(f"Verified {count} variant transitions with default bindings")


if __name__ == "__main__":
    main()
